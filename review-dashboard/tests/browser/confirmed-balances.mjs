import assert from 'node:assert/strict';

export async function runConfirmedBalances({page,base,persona,expect,control,go,overflow,snap,record,quiesce,resetDrafts}) {
  await quiesce();await control('reset-review',{});await resetDrafts({persona,empty:true});await control('gate',{state:'ready'});
  const seed=await control('confirmed-balances',{});
  const get=async path=>{const response=await fetch(base+'api/'+path);assert.ok(response.ok);return response.json();};
  await go('add/');const words=page.locator('#expense-words');
  await words.fill('Cedar learning on 30 October');
  const guess=page.getByRole('complementary',{name:'Usual payment'});
  await expect(guess).toBeVisible();await guess.getByLabel('Payment date').fill('2026-10-30');
  await guess.getByRole('checkbox',{name:/Add another anyway/}).check();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/usual')&&r.request().method()==='POST');
  await guess.getByRole('button',{name:'Add as usual'}).click();
  const response=await responsePromise;assert.equal(response.status(),200);assert.equal((await response.json()).refusal.kind,'confirmed_balance');
  const notice=page.getByRole('alert',{name:'Confirmed balance refusal'});
  await expect(notice).toContainText('Cedar Current’s October balance is already confirmed');
  await expect(notice.getByRole('link',{name:'View entry'})).toHaveCount(1);
  await expect(words).toHaveValue('Cedar learning on 30 October');
  await expect(notice.getByRole('button',{name:'Change account or date'})).toBeVisible();
  await expect(notice.getByRole('button',{name:'Keep as draft'})).toBeVisible();
  await overflow('confirmed Add refusal');await snap('confirmed-usual-refusal');
  let failed=(await get('drafts')).find(d=>d.refusal);assert.ok(failed);
  await notice.getByRole('button',{name:'Change account or date'}).click();
  await expect(notice).toHaveCount(0);await expect(words).toHaveValue('Cedar learning on 30 October');
  assert.equal((await get('drafts/'+failed.id)).state,'editing');
  await expect(guess.getByRole('button',{name:'Add as usual'})).toBeEnabled();await guess.getByRole('button',{name:'Add as usual'}).click();await expect(notice).toBeVisible();
  await notice.getByRole('button',{name:'Keep as draft'}).click();await expect(notice).toHaveCount(0);
  assert.equal((await get('drafts/'+failed.id)).state,'editing');
  await expect(guess.getByRole('button',{name:'Add as usual'})).toBeEnabled();await guess.getByRole('button',{name:'Add as usual'}).click();await expect(notice).toBeVisible();
  await notice.getByRole('button',{name:'Discard',exact:true}).click();await expect(notice).toHaveCount(0);await expect(words).toHaveValue('');
  await words.fill('Cedar learning on 30 October');await expect(guess).toBeVisible();await guess.getByLabel('Payment date').fill('2026-10-30');await guess.getByRole('checkbox',{name:/Add another anyway/}).check();
  await guess.getByRole('button',{name:'Add as usual'}).click();await expect(notice).toBeVisible();
  failed=(await get('drafts')).find(d=>d.refusal);assert.ok(failed);
  await go('drafts/?draft='+failed.id);
  await expect(notice).toContainText('confirmed');await expect(page.getByRole('button',{name:'Retry',exact:true})).toHaveCount(0);
  await expect(notice.getByRole('button',{name:'Finish it yourself'})).toBeVisible();await snap('confirmed-draft-refusal');
  await notice.getByRole('button',{name:'Finish it yourself'}).click();
  const hand=page.getByRole('article',{name:'Finish it yourself'});
  await hand.getByRole('button',{name:'Check entry',exact:true}).click();await expect(hand.getByRole('alert')).toContainText('already confirmed');
  await overflow('confirmed hand refusal');await snap('confirmed-hand-refusal');
  await hand.getByRole('button',{name:'Keep as draft'}).click();
  await expect(hand).toHaveCount(0); // Release and saved-form persistence finish before fixture deletion.
  await quiesce();await resetDrafts({persona,empty:true});
  const created=await fetch(base+'api/drafts',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({text:'Another Cedar learning payment'})});
  const agentDraft=await created.json();assert.equal(created.status,201);
  assert.ok((await fetch(base+`api/drafts/${agentDraft.id}/save`,{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'})).ok);
  await expect.poll(async()=>(await get('drafts/'+agentDraft.id)).state,{timeout:180000}).toBe('failed');
  await go('drafts/?draft='+agentDraft.id);await expect(notice).toContainText('already confirmed');await expect(page.getByRole('button',{name:'Retry',exact:true})).toHaveCount(0);await snap('confirmed-agent-refusal');
  await quiesce();await go('explorer/?month=2026-10&entry='+seed.entry_id);
  await page.getByRole('dialog').getByRole('button',{name:'Correct this entry'}).click();
  const form=page.getByRole('article',{name:'Correct this entry',exact:true});
  await expect(form).toContainText('Amount and paying account are locked by the Cedar Current statement to');
  await expect(form.getByRole('group',{name:'Posting 2',exact:true}).getByLabel('Amount',{exact:true})).toHaveAttribute('readonly','');
  await expect(form.getByRole('group',{name:'Posting 2',exact:true}).getByLabel('Account',{exact:true})).toHaveAttribute('readonly','');
  await expect(form.getByLabel('Date',{exact:true})).toHaveAttribute('max','2026-10-31');
  await expect(form.getByLabel('Description',{exact:true})).toBeEditable();
  await overflow('confirmed correction lock');await snap('confirmed-correction-lock');
  await form.getByLabel('Date',{exact:true}).fill('2026-10-31');
  await form.getByRole('button',{name:'Check entry',exact:true}).click();
  await expect(form.getByRole('alert')).toContainText('before the closing entry on the same day');
  await snap('confirmed-same-day-refusal');
  await form.getByRole('button',{name:'Back',exact:true}).click();await page.getByRole('button',{name:'Close details'}).click();
  await quiesce();const receipt=await control('confirmed-receipt',{});await go('drafts/?draft='+receipt.id);
  const reading=page.getByRole('region',{name:'Receipt reading'});
  await reading.getByRole('button',{name:'Use the receipt'}).click();
  await expect(reading.getByRole('alert')).toContainText('already confirmed');await snap('confirmed-receipt-refusal');
  await reading.getByRole('button',{name:'Keep the entry'}).click();await expect(reading).toContainText('Entry kept. Receipt notes saved.',{timeout:180000});
  record('6f confirmed balance refusal, duplicates, retained words, no Retry, hand refusal and correction date/order locks');
  await quiesce();await control('reset-review',{});await resetDrafts({persona,empty:true});
}
